-- Ciphertext and bounded transport metadata only. No endpoint key or task execution authority.
CREATE TABLE remote_private_messages (
 owner_id uuid NOT NULL REFERENCES remote_accounts(id) ON DELETE CASCADE,
 message_id uuid NOT NULL,
 sender_id uuid NOT NULL,
 recipient_id uuid NOT NULL,
 sender_kind text NOT NULL CHECK(sender_kind IN ('browser','mac')),
 sender_permission_id uuid NOT NULL,
 recipient_permission_id uuid NOT NULL,
 sender_key_epoch bigint NOT NULL CHECK(sender_key_epoch>0 AND sender_key_epoch<=9007199254740991),
 recipient_key_epoch bigint NOT NULL CHECK(recipient_key_epoch>0 AND recipient_key_epoch<=9007199254740991),
 sequence bigint NOT NULL CHECK(sequence>0 AND sequence<=9007199254740991),
 envelope_hash char(64) NOT NULL CHECK(envelope_hash ~ '^[0-9a-f]{64}$'),
 envelope jsonb,
 content_bytes integer NOT NULL CHECK(content_bytes>=0 AND content_bytes<=98304),
 revision bigint NOT NULL CHECK(revision>0 AND revision<=9007199254740991),
 state text NOT NULL CHECK(state IN ('stored','received','deleted')),
 stored_at bigint NOT NULL CHECK(stored_at>0),
 expires_at bigint NOT NULL CHECK(expires_at>stored_at),
 received_at bigint,
 ack_revision bigint,
 deleted_at bigint,
 delete_base_revision bigint,
 received_policy text NOT NULL CHECK(received_policy IN ('delete-after-receipt','until-deleted')),
 unreceived_purge_at bigint,
 metadata_retention_ms bigint NOT NULL CHECK(metadata_retention_ms IN (604800000,2592000000)),
 metadata_purge_at bigint,
 PRIMARY KEY(owner_id,message_id),
 UNIQUE(owner_id,sender_id,recipient_id,sender_key_epoch,recipient_key_epoch,sequence),
 CHECK(sender_id<>recipient_id),
 CHECK((envelope IS NULL)=(content_bytes=0)),
 CHECK(envelope IS NULL OR jsonb_typeof(envelope)='object'),
 CHECK((state='deleted')=(delete_base_revision IS NOT NULL)),
 CHECK(state<>'stored' OR envelope IS NOT NULL),
 CHECK(state<>'deleted' OR envelope IS NULL),
 CHECK((received_at IS NULL)=(ack_revision IS NULL)),
 CHECK(ack_revision IS NULL OR (ack_revision>1 AND ack_revision<=revision)),
 CHECK(delete_base_revision IS NULL OR (delete_base_revision>0 AND delete_base_revision<revision)),
 CHECK(received_at IS NULL OR received_at>=stored_at),
 CHECK(deleted_at IS NULL OR deleted_at>=stored_at),
 CHECK((envelope IS NULL)=(metadata_purge_at IS NOT NULL)),
 CHECK(unreceived_purge_at IS NULL OR unreceived_purge_at>stored_at),
 CHECK(metadata_purge_at IS NULL OR metadata_purge_at>expires_at)
);
CREATE INDEX remote_private_messages_poll ON remote_private_messages(owner_id,recipient_permission_id,stored_at,message_id) WHERE state='stored';
CREATE INDEX remote_private_messages_pending_expiry ON remote_private_messages(unreceived_purge_at) WHERE state='stored' AND unreceived_purge_at IS NOT NULL;
CREATE INDEX remote_private_messages_metadata_expiry ON remote_private_messages(metadata_purge_at) WHERE metadata_purge_at IS NOT NULL;
